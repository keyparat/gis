/**
 * WebGIS QGIS Viewer - Vercel Serverless Adapter
 * Re-implements the original request handler for Vercel serverless functions.
 */

const http = require("http");
const fs = require("fs");
const path = require("path");

const PUBLIC_DIR = path.join(__dirname, "public");

const MIME_TYPES = {
  ".html": "text/html; charset=utf-8",
  ".css": "text/css; charset=utf-8",
  ".js": "application/javascript; charset=utf-8",
  ".json": "application/json; charset=utf-8",
  ".geojson": "application/geo+json; charset=utf-8",
  ".png": "image/png",
  ".jpg": "image/jpeg",
  ".jpeg": "image/jpeg",
  ".svg": "image/svg+xml",
  ".ico": "image/x-icon"
};

const createRequestHandler = () => {
  return (req, res) => {
    if (req.method === "OPTIONS") {
      res.writeHead(204, {
        "Access-Control-Allow-Origin": "*",
        "Access-Control-Allow-Methods": "GET, OPTIONS"
      });
      res.end();
      return;
    }

    res.setHeader("Access-Control-Allow-Origin", "*");
    res.setHeader("Access-Control-Allow-Methods", "GET, OPTIONS");
    res.setHeader("Access-Control-Allow-Headers", "Content-Type, Authorization");

    let reqPath = decodeURI(req.url.split("?")[0]);
    if (reqPath === "/" || reqPath === "") {
      reqPath = "/index.html";
    }

    const relativePath = reqPath.replace(/^\/+/, "");
    const filePath = path.normalize(path.join(PUBLIC_DIR, relativePath));
    const publicDirNormalized = path.normalize(PUBLIC_DIR);

    if (!filePath.startsWith(publicDirNormalized + path.sep) && filePath !== publicDirNormalized) {
      res.writeHead(403, { "Content-Type": "text/plain; charset=utf-8" });
      res.end("403 Forbidden");
      return;
    }

    fs.stat(filePath, (err, stats) => {
      if (err || !stats.isFile()) {
        const isKnownAsset = /\.(html|css|js|json|geojson|png|jpg|jpeg|svg|ico|webp|avif)$/i.test(reqPath);
        if (isKnownAsset) {
          res.writeHead(404, { "Content-Type": "text/plain; charset=utf-8" });
          res.end("404 Not Found: " + reqPath);
          return;
        }

        res.writeHead(200, { "Content-Type": "text/html; charset=utf-8" });
        fs.createReadStream(path.join(PUBLIC_DIR, "index.html")).pipe(res);
        return;
      }

      const ext = path.extname(filePath).toLowerCase();
      const contentType = MIME_TYPES[ext] || "application/octet-stream";
      res.writeHead(200, { "Content-Type": contentType });
      fs.createReadStream(filePath).pipe(res);
    });
  };
};

const PORT = process.env.PORT || 8080;
const server = http.createServer(createRequestHandler());

module.exports = server;

